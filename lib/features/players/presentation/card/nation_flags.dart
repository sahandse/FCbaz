String? nationFlagEmoji(String nation) {
  final key = nation.trim().toLowerCase();
  if (key.isEmpty) return null;
  final home = _homeNations[key];
  if (home != null) return home;
  final iso = _nationIso[key];
  if (iso == null || iso.length != 2) return null;
  return String.fromCharCodes(iso.codeUnits.map((unit) => unit + 127397));
}
