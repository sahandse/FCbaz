  List<DnsServer> getAll() => defaultServers;

  List<DnsServer> filter({String category = 'all', String query = ''}) {
    final q = query.trim().toLowerCase();
    return defaultServers.where((server) {
      if (category != 'all' && server.category != category) {
        return false;
      }
      if (q.isEmpty) return true;
      return server.name.toLowerCase().contains(q) ||
          server.nameEn.toLowerCase().contains(q) ||
          server.badge.toLowerCase().contains(q) ||
          server.desc.toLowerCase().contains(q) ||
          server.suitable.toLowerCase().contains(q) ||
          server.primary.contains(q) ||
          server.secondary.contains(q);
    }).toList();
  }

  int countForCategory(String category) {
    if (category == 'all') return defaultServers.length;
    return defaultServers.where((s) => s.category == category).length;
  }
}
